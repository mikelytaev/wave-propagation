    def test_impedance_ground_vs_fd(self):
        params = RWPComputationalParams(max_range_m=5000.0, max_height_m=300.0, dx_m=50.0, dz_m=1.0, precision=0.01)
        for pol, eps, sigma in (('V', 3.0, 0.0), ('H', 80.0, 4.0)):
            with self.subTest(pol=pol, eps=eps, sigma=sigma):
                with TestReport(self, f"""
                    Finite-permittivity ground (eps = {eps}, sigma = {sigma} S/m),
                    {pol}-polarisation, standard atmosphere, 300 MHz, 5 km. SSW
                    propagates the DMFT variable w with the wavelet scheme and the
                    surface-wave modes analytically; it is compared with the Padé FD
                    solver (nonlocal boundary condition) and with SSF.
                    """, title=f"SSW impedance ground {pol}-pol eps={eps:g}", suffix=f"{pol}_eps{eps:g}") as rep:
                    src = RWPGaussSourceModel(freq_hz=300e6, height_m=30.0, beam_width_deg=5.0, polarization=pol)
                    env = TroposphereModel(ground_material=GroundMaterial(eps=eps, sigma=sigma))
                    _ssw_setup(rep, src, env, params)
                    ssw = _run(src, env, params, 'ssw')
                    ssf = _run(src, env, params, 'ssf')
