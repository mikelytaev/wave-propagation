"""
JAX-based 2D split-step wavelet (SSW) propagator for the Helmholtz equation.

The SSW method (Zhou, Douvenot & Chabory, J. Comput. Phys. 2020; Bonnafont,
Douvenot & Chabory, Radio Science 2021) follows the same marching scheme as
the split-step Fourier method, but performs the free-space step in the
domain of an orthogonal discrete wavelet basis:

1. fast wavelet transform (FWT) of the field on the vertical grid and hard
   thresholding of the coefficients (signal threshold ``V_s``);
2. free-space propagation of the sparse coefficient vector with a
   pre-computed, hard-thresholded (propagator threshold ``V_p``) operator
   built from the propagated elementary wavelets of every level;
3. inverse FWT, then the phase screen for refraction, the staircase relief,
   the Hanning apodization at the top and the ground condition.

The ground is treated with the *local image method*: before every free-space
step, an image layer of ``n_image`` points below the ground is filled with the
mirrored field (``-u`` for a Dirichlet / horizontally polarised PEC ground,
``+u`` for a Neumann ground) and cleared afterwards. A Leontovich impedance
ground is handled as in the SSW literature by propagating the discrete
mixed Fourier transform variable ``w = du/dz + alpha u`` (Dirichlet type) with
the wavelet scheme while the surface-wave amplitudes are propagated
analytically (see :class:`~pywaveprop.helmholtz_ssf_jax.DMFTBoundary`).

Compression thresholds follow the closed-form rule of Bonnafont et al. (URSI
Radio Science Letters, 2021): for a target accumulated relative error
``precision`` over ``N_x`` range steps, ``v_s = v_p = precision / (2 N_x)``,
``V_s = v_s max|W u|`` (of the current field) and ``V_p = v_p max|P|``. The propagation operator is
stored as a sparse (BCOO) matrix of the retained coefficients.

The wavelet filter banks (default: symlet 6 with 3 levels, as in the
reference papers) are generated by :mod:`pywaveprop.utils.wavelets`; the FWT
uses periodization, so the vertical grid length is a multiple of ``2**levels``.
"""
import math as fm

import jax
import jax.numpy as jnp
import numpy as np
from jax import tree_util
from jax.experimental import sparse as jsparse

jax.config.update("jax_enable_x64", True)

from pywaveprop.helmholtz_common import HelmholtzMeshParams2D
from pywaveprop.helmholtz_jax import RegularGrid, LowerLayerModel
from pywaveprop.helmholtz_ssf_jax import DMFTBoundary
from pywaveprop.utils.wavelets import filter_bank


class PeriodicFWT:
    """Multilevel periodized fast wavelet transform on ``n`` points
    (``n`` divisible by ``2**levels``) with an orthonormal filter bank.

    Coefficients are stored as one vector ``[a_L, d_L, d_{L-1}, ..., d_1]``.
    """

    def __init__(self, n: int, wavelet: str = 'sym6', levels: int = 3):
        if n % 2 ** levels:
            raise ValueError(f"grid length {n} is not divisible by 2**{levels}")
        self.n = int(n)
        self.levels = int(levels)
        self.wavelet = wavelet
        h, g = filter_bank(wavelet)
        self.h = jnp.asarray(h)
        self.g = jnp.asarray(g)
        self.support = len(h)
        if self.n // 2 ** levels < len(h):
            raise ValueError("coarsest level shorter than the wavelet filter; reduce levels")
        self._idx = []
        m = np.arange(len(h))
        size = self.n
        for _ in range(levels):
            k = np.arange(size // 2)
            self._idx.append(jnp.asarray((2 * k[:, None] + m[None, :]) % size))
            size //= 2
        self.sizes = [self.n // 2 ** l for l in range(1, levels + 1)]

    def forward(self, x):
        x = jnp.asarray(x)
        details = []
        for idx in self._idx:
            gathered = x[idx]
            a = gathered @ self.h
            d = gathered @ self.g
            details.append(d)
            x = a
        return jnp.concatenate([x] + details[::-1])

    def inverse(self, coefs):
        n_c = self.sizes[-1]
        a = coefs[:n_c]
        pos = n_c
        for level in range(self.levels - 1, -1, -1):
            size = self.sizes[level]
            d = coefs[pos:pos + size]
            pos += size
            idx = self._idx[level]
            contrib = a[:, None] * self.h[None, :] + d[:, None] * self.g[None, :]
            a = jnp.zeros(2 * size, dtype=contrib.dtype).at[idx].add(contrib)
        return a

    def level_of_index(self):
        """Wavelet level (0 = scaling function) of each coefficient index."""
        out = np.zeros(self.n, dtype=int)
        pos = self.sizes[-1]
        for level in range(self.levels, 0, -1):
            size = self.n // 2 ** level
            out[pos:pos + size] = level
            pos += size
        return out


class SSWHelmholtzPropagator:
    """Split-step wavelet propagator, see the module docstring."""

    @classmethod
    def create(cls, freq_hz: float, wave_speed, kz_max, k_bounds, precision, mesh_params: HelmholtzMeshParams2D,
               lower_terrain=None, lower_bc: str = 'dirichlet', lower_impedance_alpha=None,
               lower_layer: LowerLayerModel = None, abs_layer_scale: float = 0.5,
               dx_m: float = None, dz_m: float = None, spectral_margin: float = 2.0,
               wavelet: str = 'sym6', levels: int = 3, n_image: int = None, sparse: bool = True,
               **_ignored):
        """Same grid conventions as :meth:`SSFHelmholtzPropagator.create`.

        ``precision`` is the target accumulated relative compression error
        over the whole range and sets both hard thresholds. ``n_image`` (image
        layer size in points) defaults to the wavelet support at the coarsest
        level plus twice the vertical spread ``dx tan(theta_max)`` of one step,
        and at least a tenth of the physical domain. The mirrored field must be
        negligible at the bottom of the image layer (i.e. the field must be
        negligible at height ``n_image dz``),
        otherwise the truncated image diffracts spuriously.
        """
        kz_max = float(kz_max)
        k_bounds = (float(k_bounds[0]), float(k_bounds[1]))
        beta = 0.5 * (k_bounds[0] + k_bounds[1])

        dx_max = mesh_params.dx_output_m or mesh_params.x_size_m / (round(mesh_params.x_n_upper_bound / 2) - 1)
        dz_max = mesh_params.dz_output_m or mesh_params.z_size_m / (round(mesh_params.z_n_upper_bound / 2) - 1)
        if dz_m is None:
            dz_m = min(dz_max, fm.pi / (spectral_margin * kz_max))
        sin_theta = min(max(kz_max / beta, 1e-3), 1.0)
        if dx_m is None:
            dx_m = min(dx_max, 2 * fm.pi / (beta * sin_theta ** 2))

        if mesh_params.dx_output_m:
            x_output_step = fm.ceil(mesh_params.dx_output_m / dx_m)
            dx_m = mesh_params.dx_output_m / x_output_step
        else:
            x_output_step = fm.floor(dx_max / dx_m)
            dx_m = dx_max / x_output_step
        if mesh_params.dz_output_m:
            z_output_step = fm.ceil(mesh_params.dz_output_m / dz_m)
            dz_m = mesh_params.dz_output_m / z_output_step
        else:
            z_output_step = fm.floor(dz_max / dz_m)
            dz_m = dz_max / z_output_step

        x_n = fm.ceil(mesh_params.x_size_m / dx_m) + 1
        z_n_phys = fm.ceil(mesh_params.z_size_m / dz_m) + 1
        z_n_abs = fm.ceil(abs_layer_scale * mesh_params.z_size_m / dz_m)
        h, _ = filter_bank(wavelet)
        if n_image is None:
            # wavelet support at the coarsest level + twice the vertical spread of
            # one step, with the 0.1 z_max floor used in the SSW literature
            tan_theta = sin_theta / fm.sqrt(1 - sin_theta ** 2)
            n_image = max((len(h) - 1) * 2 ** levels + fm.ceil(2 * dx_m * tan_theta / dz_m),
                          fm.ceil(0.1 * z_n_phys))
        block = 2 ** levels
        n_total = fm.ceil((n_image + z_n_phys + z_n_abs) / block) * block
        z_n = n_total - n_image  # points from the ground to the top of the apodization layer

        print(f'ssw: beta: {beta}, dx: {dx_m}, dz: {dz_m}, z_n: {z_n} (abs layer: {z_n - z_n_phys}), '
              f'image layer: {n_image}, wavelet: {wavelet}, levels: {levels}')

        return cls(
            beta=beta, dx_m=dx_m, dz_m=dz_m, x_n=x_n, z_n=z_n, z_n_phys=z_n_phys,
            x_grid_scale=x_output_step, z_grid_scale=z_output_step, freq_hz=freq_hz,
            wave_speed=wave_speed, lower_terrain=lower_terrain, lower_bc=lower_bc,
            lower_impedance_alpha=lower_impedance_alpha, lower_layer=lower_layer,
            wavelet=wavelet, levels=levels, n_image=n_image, precision=float(precision), sparse=sparse,
        )

    def __init__(self, beta: float, dx_m: float, dz_m: float, x_n: int, z_n: int, z_n_phys: int,
                 x_grid_scale: int, z_grid_scale: int, freq_hz: float, wave_speed,
                 lower_terrain=None, lower_bc: str = 'dirichlet', lower_impedance_alpha=None,
                 lower_layer: LowerLayerModel = None, wavelet: str = 'sym6', levels: int = 3,
                 n_image: int = 64, precision: float = 0.01, sparse: bool = True,
                 wavelet_propagator=None):
        if lower_bc not in ('dirichlet', 'neumann', 'impedance'):
            raise ValueError(f"unknown lower_bc {lower_bc!r}; expected 'dirichlet', 'neumann' or 'impedance'")
        if lower_bc == 'impedance' and lower_impedance_alpha is None:
            raise ValueError("lower_bc='impedance' requires lower_impedance_alpha")
        self.beta = float(beta)
        self.dx_m = float(dx_m)
        self.dz_m = float(dz_m)
        self.x_n = int(x_n)
        self.z_n = int(z_n)
        self.z_n_phys = int(z_n_phys)
        self.x_grid_scale = int(x_grid_scale)
        self.z_grid_scale = int(z_grid_scale)
        self.freq_hz = freq_hz
        self.wave_speed = wave_speed
        self.lower_terrain = lower_terrain
        self.lower_bc = lower_bc
        self.lower_impedance_alpha = None if lower_impedance_alpha is None else complex(lower_impedance_alpha)
        self.lower_layer = lower_layer
        self.wavelet = wavelet
        self.levels = int(levels)
        self.n_image = int(n_image)
        self.precision = float(precision)
        self.sparse = bool(sparse)
        self.n_total = self.n_image + self.z_n
        self.fwt = PeriodicFWT(self.n_total, wavelet, self.levels)
        # normalised thresholds v_s = v_p = precision / (2 N_x)  (Bonnafont et al. 2021)
        self.v_threshold = self.precision / (2 * max(self.x_n - 1, 1))
        self._prepare_arrays()
        self._prop = wavelet_propagator if wavelet_propagator is not None else self._build_propagator()

    # ------------------------------------------------------------------ setup
    def _prepare_arrays(self):
        z_grid = RegularGrid(start=0, dx=self.dz_m, n=self.z_n)
        k_arr = 2 * jnp.pi * self.freq_hz / self.wave_speed.on_regular_grid(z_grid)
        self.het = jnp.array(k_arr ** 2 / self.beta ** 2 - 1.0, dtype=complex)

        # Hanning apodization above the physical domain
        z = np.arange(self.z_n) * self.dz_m
        z_phys = (self.z_n_phys - 1) * self.dz_m
        z_top = (self.z_n - 1) * self.dz_m
        if self.z_n > self.z_n_phys:
            t = np.clip((z - z_phys) / (z_top - z_phys), 0.0, 1.0)
            self._abs_window = jnp.asarray(0.5 * (1 + np.cos(np.pi * t)))
        else:
            self._abs_window = jnp.ones(self.z_n)

        x_grid = RegularGrid(start=0, dx=self.dx_m, n=self.x_n)
        self._z_indices = jnp.arange(self.z_n)
        if self.lower_terrain is not None:
            self.lower_terrain_idx = jnp.round(
                self.lower_terrain.on_regular_grid(x_grid) / self.dz_m).astype(jnp.int64)
        else:
            self.lower_terrain_idx = jnp.zeros(self.x_n, dtype=jnp.int64)
        if self.lower_layer is not None:
            self.layer_idx = jnp.round(
                self.lower_layer.thickness.on_regular_grid(x_grid) / self.dz_m).astype(jnp.int64)
            self.layer_delta_het = jnp.asarray(self.lower_layer.k2_contrast / self.beta ** 2, dtype=complex)
        else:
            self.layer_idx = jnp.zeros(self.x_n, dtype=jnp.int64)
            self.layer_delta_het = jnp.asarray(0.0, dtype=complex)

        if self.lower_bc == 'impedance':
            self._dmft = DMFTBoundary(self.lower_impedance_alpha, self.dz_m, self.z_n, self.beta, self.dx_m)

    def _free_space_multiplier(self):
        """Exact free-space step on the periodic full grid (image layer + domain)."""
        p = 2 * np.pi * np.fft.fftfreq(self.n_total, d=self.dz_m)
        kx = np.sqrt(self.beta ** 2 - p.astype(complex) ** 2)
        kx = np.where(kx.imag < 0, -kx, kx)
        return jnp.asarray(np.exp(1j * self.dx_m * (kx - self.beta)))

    def _build_propagator(self):
        """Wavelet-domain free-space operator ``P = W P_space W^T``: every
        elementary wavelet (column of ``W^T``) is propagated with the exact
        spectral step and decomposed again; entries below ``V_p`` are dropped."""
        n = self.n_total
        basis = jax.vmap(self.fwt.inverse)(jnp.eye(n, dtype=complex))          # row k: wavelet k in space
        propagated = jnp.fft.ifft(jnp.fft.fft(basis, axis=1) * self._free_space_multiplier()[None, :], axis=1)
        columns = jax.vmap(self.fwt.forward)(propagated)                         # row k: coefficients of P wavelet_k
        prop = columns.T
        v_p = self.v_threshold * jnp.max(jnp.abs(prop))
        prop = jnp.where(jnp.abs(prop) > v_p, prop, 0.0)
        self.propagator_density = float(jnp.count_nonzero(prop)) / n ** 2
        if self.sparse:
            return jsparse.BCOO.fromdense(prop)
        return prop

    # ------------------------------------------------------------------ grids
    def x_computational_grid(self):
        return jnp.arange(0, self.x_n) * self.dx_m

    def x_output_grid(self):
        return self.x_computational_grid()[::self.x_grid_scale]

    def z_computational_grid(self):
        """Grid from the ground to the top of the apodization layer (image layer excluded)."""
        return jnp.arange(0, self.z_n) * self.dz_m

    def z_physical_grid(self):
        return jnp.arange(0, self.z_n_phys) * self.dz_m

    def z_output_grid(self):
        return self.z_physical_grid()[::self.z_grid_scale]

    def terrain_mask_row(self, i):
        return jnp.where(self._z_indices >= self.lower_terrain_idx[i], 1.0 + 0.0j, 0.0 + 0.0j)

    def het_row(self, i):
        if self.lower_layer is None:
            return self.het
        lo = self.lower_terrain_idx[i]
        inside = (self._z_indices >= lo) & (self._z_indices < lo + self.layer_idx[i])
        return self.het + self.layer_delta_het * inside

    # ----------------------------------------------------------------- pytree
    def _tree_flatten(self):
        dynamic = (self.wave_speed, self.lower_terrain, self.lower_layer, self._prop)
        static = {
            'beta': self.beta, 'dx_m': self.dx_m, 'dz_m': self.dz_m, 'x_n': self.x_n, 'z_n': self.z_n,
            'z_n_phys': self.z_n_phys, 'x_grid_scale': self.x_grid_scale, 'z_grid_scale': self.z_grid_scale,
            'freq_hz': self.freq_hz, 'lower_bc': self.lower_bc, 'lower_impedance_alpha': self.lower_impedance_alpha,
            'wavelet': self.wavelet, 'levels': self.levels, 'n_image': self.n_image,
            'precision': self.precision, 'sparse': self.sparse,
        }
        return dynamic, static

    @classmethod
    def _tree_unflatten(cls, static, dynamic):
        return cls(wave_speed=dynamic[0], lower_terrain=dynamic[1], lower_layer=dynamic[2],
                   wavelet_propagator=dynamic[3], **static)

    # ------------------------------------------------------------- stepping
    def wavelet_coefficients(self, u):
        """Compressed wavelet coefficients of a field on the full grid (diagnostics)."""
        return self.fwt.forward(u)

    def _free_space_step(self, v, image_sign):
        """One free-space step of a field ``v`` on the domain grid (ground .. top)
        with the local image method (``image_sign`` = -1 Dirichlet, +1 Neumann).

        The signal threshold is ``v_s`` times the largest coefficient of the
        current field (rather than of the initial field as in Bonnafont et al.
        2021), so that strongly attenuated fields keep their relative accuracy.
        """
        image = image_sign * v[self.n_image:0:-1]
        full = jnp.concatenate((image, v))
        coefs = self.fwt.forward(full)
        coefs = jnp.where(jnp.abs(coefs) > self.v_threshold * jnp.max(jnp.abs(coefs)), coefs, 0.0)
        coefs = self._prop @ coefs
        full = self.fwt.inverse(coefs)
        return full[self.n_image:]

    def _propagate(self, u):
        if self.lower_bc == 'dirichlet':
            return self._free_space_step(u, -1.0)
        if self.lower_bc == 'neumann':
            return self._free_space_step(u, 1.0)
        w, _, a_sw, b_sw = self._dmft.forward(u)
        zero = jnp.zeros(1, dtype=complex)
        w_full = jnp.concatenate((zero, w, zero))
        w_full = self._free_space_step(w_full, -1.0)
        c = self._dmft.sine_coefs(w_full[1:-1])
        a_sw, b_sw = self._dmft.propagate_surface(a_sw, b_sw)
        return self._dmft.inverse(c, a_sw, b_sw)

    def _step(self, u, het):
        phase_half = jnp.exp(0.5j * self.dx_m * self.beta * (jnp.sqrt(1.0 + het) - 1.0))
        u = phase_half * u
        u = self._propagate(u)
        u = phase_half * u
        return u * self._abs_window

    @jax.jit
    def compute(self, initial):
        """Propagate ``initial`` (on :meth:`z_computational_grid` or
        :meth:`z_physical_grid`; zero-padded upwards) and return the field on
        the output grid, shape ``(len(x_output_grid), len(z_output_grid))``."""
        initial = jnp.asarray(initial, dtype=complex)
        u0 = jnp.zeros(self.z_n, dtype=complex).at[:initial.shape[0]].set(initial[:self.z_n])
        u0 = u0 * self.terrain_mask_row(0)

        n_x_out = (self.x_n - 1) // self.x_grid_scale + 1
        n_z_out = (self.z_n_phys - 1) // self.z_grid_scale + 1
        results = jnp.zeros((n_x_out, n_z_out), dtype=complex)
        results = results.at[0, :].set(u0[:self.z_n_phys:self.z_grid_scale])

        def body_fun(i, val):
            u, res = val
            u = self._step(u, self.het_row(i))
            u = u * self.terrain_mask_row(i)
            res = jax.lax.cond(i % self.x_grid_scale == 0,
                               lambda: res.at[i // self.x_grid_scale, :].set(u[:self.z_n_phys:self.z_grid_scale]),
                               lambda: res)
            return u, res

        _, results = jax.lax.fori_loop(1, self.x_n, body_fun, (u0, results))
        return results


tree_util.register_pytree_node(SSWHelmholtzPropagator,
                               SSWHelmholtzPropagator._tree_flatten,
                               SSWHelmholtzPropagator._tree_unflatten)
